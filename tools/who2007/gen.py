"""
Writes the WHO 2007 growth reference tables (5-19 years) into the Worker, the
Android app and the iOS app, from the WHO's own files beside this script.

    python tools/who2007/gen.py

Source: github.com/WorldHealthOrganization/anthroplus, data-raw/growthstandards
(bfawho2007.txt = BMI-for-age, hfawho2007.txt = height-for-age,
wfawho2007.txt = weight-for-age). Each row is sex (1 boy, 2 girl), age in
completed months, and the L, M, S that define the curve at that month: 60-229
for BMI and height, 60-120 for weight, which the WHO stops at 10 years because
weight alone cannot tell a tall child from a heavy one past that age (its file
repeats month 120 as 121; that row is dropped). Copy new versions of the files here and
run this again; never edit the generated files by hand. functions/who2007.test.ts
fails if the three copies disagree.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))


def read(name, last=229):
    out = {1: ([], [], []), 2: ([], [], [])}
    ages = {1: [], 2: []}
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        next(f)
        for line in f:
            sex, age, l, m, s = line.split()
            sex = int(sex)
            if int(age) > last:
                continue
            ages[sex].append(int(age))
            # Kotlin's doubleArrayOf takes no bare integers; the WHO writes L as "1" in places.
            l, m, s = (v if "." in v else v + ".0" for v in (l, m, s))
            out[sex][0].append(l)
            out[sex][1].append(m)
            out[sex][2].append(s)
    for sex in (1, 2):
        assert ages[sex] == list(range(60, last + 1)), name
    return out


TABLES = {"BFA": read("bfawho2007.txt"), "HFA": read("hfawho2007.txt"),
          "WFA": read("wfawho2007.txt", last=120)}
HEAD = "GENERATED by tools/who2007/gen.py from the WHO 2007 reference files. Do not edit."


def rows(vals, indent):
    lines = []
    for i in range(0, len(vals), 10):
        lines.append(indent + ", ".join(vals[i:i + 10]) + ",")
    return "\n".join(lines)


def ts():
    out = [f"// {HEAD}", "// L, M, S by completed month of age, 60 to 229 (weight: 60 to 120), index = month - 60.", ""]
    out.append("export interface Lms { L: number[]; M: number[]; S: number[] }")
    for name, t in TABLES.items():
        for sex, key in ((1, "M"), (2, "F")):
            out.append(f"export const {name}_{key}: Lms = {{")
            for part, vals in zip("LMS", t[sex]):
                out.append(f"  {part}: [\n{rows(vals, '    ')}\n  ],")
            out.append("};")
    return "\n".join(out) + "\n"


def kt():
    out = ["package kallam.healthcare.data", "", f"// {HEAD}",
           "// L, M, S by completed month of age, 60 to 229 (weight: 60 to 120), index = month - 60.",
           "internal object WhoTables {",
           "    class Lms(val l: DoubleArray, val m: DoubleArray, val s: DoubleArray)"]
    for name, t in TABLES.items():
        for sex, key in ((1, "M"), (2, "F")):
            out.append(f"    val {name}_{key} = Lms(")
            for vals in t[sex]:
                out.append(f"        doubleArrayOf(\n{rows(vals, '            ')}\n        ),")
            out.append("    )")
    out.append("}")
    return "\n".join(out) + "\n"


def swift():
    out = [f"// {HEAD}", "// L, M, S by completed month of age, 60 to 229 (weight: 60 to 120), index = month - 60.",
           "enum WhoTables {",
           "    struct Lms { let l: [Double]; let m: [Double]; let s: [Double] }"]
    for name, t in TABLES.items():
        for sex, key in ((1, "M"), (2, "F")):
            out.append(f"    static let {name}_{key} = Lms(")
            labels = ("l", "m", "s")
            for i, vals in enumerate(t[sex]):
                comma = "," if i < 2 else ""
                out.append(f"        {labels[i]}: [\n{rows(vals, '            ')}\n        ] as [Double]{comma}")
            out.append("    )")
    out.append("}")
    return "\n".join(out) + "\n"


def write(rel, text):
    p = os.path.join(ROOT, rel)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", rel)


write("functions/who2007-data.ts", ts())
write("android/app/src/main/java/kallam/healthcare/data/WhoTables.kt", kt())
write("ios/VitaHero/Models/WhoTables.swift", swift())
