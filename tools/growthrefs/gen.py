"""
Writes the IAP 2015 growth charts (5-18 years) and the Mramba 2017 MUAC-for-age
reference (5-19 years) into the Worker, the Android app and the iOS app, from
the files beside this script.

    python tools/growthrefs/gen.py

iap2015.txt is Tables II-VII of the IAP paper as printed: centiles at every
half year from 5 to 18. The chart lines are drawn from those printed values.
A child between two printed lines is read between them, so the centile always
agrees with the chart. Beyond the outer lines the paper gives nothing, so the
distance past the line is read off an LMS curve fitted here to each half year's
row: M is the printed 50th, and L and S are the pair whose curve sits closest,
in least squares, to all seven printed centiles (BMI: 3rd to 50th and the 23 and
27 adult-equivalent lines, which are the 71st and 90th for boys and the 75th
and 95th for girls). The printed centiles are not exactly one LMS curve, so the
fit is close, not exact; the script prints how close and stops past 0.75.

muac_mramba2017.txt is the authors' own L, M, S by month, 60-228.

Never edit the generated files by hand. functions/growthrefs.test.ts fails if
the three copies disagree.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
HEAD = "GENERATED by tools/growthrefs/gen.py from the IAP 2015 and Mramba 2017 tables. Do not edit."


def qnorm(p):
    """Inverse normal CDF by bisection; plenty for six places."""
    lo, hi = -10.0, 10.0
    for _ in range(200):
        mid = (lo + hi) / 2
        if 0.5 * math.erfc(-mid / math.sqrt(2)) < p:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def at_z(l, m, s, z):
    if l == 0:
        return m * math.exp(s * z)
    base = 1 + l * s * z
    if base <= 0:
        raise ValueError("off the curve")
    return m * base ** (1 / l)


def z_of(l, m, s, y):
    return math.log(y / m) / s if l == 0 else ((y / m) ** l - 1) / (l * s)


def s_for(l, m, y, z):
    return math.log(y / m) / z if abs(l) < 1e-9 else ((y / m) ** l - 1) / (l * z)


def golden(f, a, b, n=80):
    g = (math.sqrt(5) - 1) / 2
    c, d = b - g * (b - a), a + g * (b - a)
    fc, fd = f(c), f(d)
    for _ in range(n):
        if fc < fd:
            b, d, fd = d, c, fc
            c = b - g * (b - a); fc = f(c)
        else:
            a, c, fc = c, d, fd
            d = a + g * (b - a); fd = f(d)
    return (a + b) / 2


def fit(m, vals, zs):
    """The L and S whose curve, through the printed median, sits closest to every printed centile."""
    def err(l, s):
        try:
            return sum((at_z(l, m, s, z) - v) ** 2 for v, z in zip(vals, zs))
        except (ValueError, ZeroDivisionError, OverflowError):
            return 1e9
    # Past 1 / (|L| z) the curve has no value at the outer centile; keep S inside that.
    top = lambda l: min(0.6, 0.999 / (abs(l) * max(abs(z) for z in zs))) if l else 0.6
    best_s = lambda l: golden(lambda s: err(l, s), 0.002, top(l))
    # The error is not unimodal in L over the whole range: a coarse grid first, then refine.
    l0 = min((i / 20 for i in range(-100, 101)), key=lambda l: err(l, best_s(l)))
    l = golden(lambda l: err(l, best_s(l)), l0 - 0.05, l0 + 0.05)
    return l, best_s(l)


# name -> (centile labels, the centiles as percentages)
CENTILES = {
    "HT": (["3", "10", "25", "50", "75", "90", "97"], [3, 10, 25, 50, 75, 90, 97]),
    "WT": (["3", "10", "25", "50", "75", "90", "97"], [3, 10, 25, 50, 75, 90, 97]),
    "BMI_M": (["3", "5", "10", "25", "50", "23 AE", "27 AE"], [3, 5, 10, 25, 50, 71, 90]),
    "BMI_F": (["3", "5", "10", "25", "50", "23 AE", "27 AE"], [3, 5, 10, 25, 50, 75, 95]),
}


def read_iap():
    rows = {}
    with open(os.path.join(HERE, "iap2015.txt"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            t = line.split()
            rows.setdefault((t[0], t[1]), []).append([float(x) for x in t[2:]])
    out = {}
    worst = worst_z = 0.0
    for (name, sex), rs in rows.items():
        assert [r[0] for r in rs] == [5 + i / 2 for i in range(27)], (name, sex)
        labels, pct = CENTILES[name if name != "BMI" else f"BMI_{sex}"]
        zs = [qnorm(p / 100) for p in pct]
        mid = pct.index(50)
        L, M, S = [], [], []
        for r in rs:
            vals = r[1:8]
            l, s = fit(vals[mid], vals, zs)
            L.append(l); M.append(vals[mid]); S.append(s)
            for v, z in zip(vals, zs):
                d = abs(at_z(l, vals[mid], s, z) - v)
                worst = max(worst, d)
                assert d <= 0.75, (name, sex, r[0], v, round(at_z(l, vals[mid], s, z), 2))
            # In z, which is what a child's reading reports.
            for v, z in zip(vals, zs):
                worst_z = max(worst_z, abs(z_of(l, vals[mid], s, v) - z))
        cols = [[r[1 + k] for r in rs] for k in range(7)]
        out[f"IAP_{name}_{sex}"] = (labels, pct, cols, L, M, S)
    print(f"IAP: fitted curves sit within {worst:.2f} (cm, kg or kg/m2) and {worst_z:.3f} z of every printed centile")
    return out


def read_muac():
    t = {1: ([], [], []), 2: ([], [], [])}
    ages = {1: [], 2: []}
    with open(os.path.join(HERE, "muac_mramba2017.txt"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            sex, age, l, m, s = line.split()
            sex = int(sex)
            ages[sex].append(int(age))
            for i, v in enumerate((l, m, s)):
                t[sex][i].append(float(v))
    for sex in (1, 2):
        assert ages[sex] == list(range(60, 229))
    return {"MUAC_M": t[1], "MUAC_F": t[2]}


IAP = read_iap()
MUAC = read_muac()


def num(v):
    s = f"{v:.10g}"
    return s if ("." in s or "e" in s) else s + ".0"


def rows(vals, indent):
    vals = [num(v) for v in vals]
    return "\n".join(indent + ", ".join(vals[i:i + 10]) + "," for i in range(0, len(vals), 10))


NOTE_IAP = "IAP 2015, 5 to 18 years at every half year (index = (age - 5) * 2): printed centiles and the fitted L, M, S."
NOTE_MUAC = "Mramba 2017 MUAC-for-age, L, M, S by completed month 60 to 228, index = month - 60."


def ts():
    out = [f"// {HEAD}", f"// {NOTE_IAP}", f"// {NOTE_MUAC}", "",
           "import type { Lms } from \"./who2007-data\";", "",
           "export interface IapChart extends Lms { labels: string[]; percents: number[]; centiles: number[][] }"]
    for name, (labels, pct, cols, L, M, S) in IAP.items():
        out.append(f"export const {name}: IapChart = {{")
        out.append("  labels: [" + ", ".join(f'"{x}"' for x in labels) + "],")
        out.append("  percents: [" + ", ".join(str(x) for x in pct) + "],")
        out.append("  centiles: [")
        for c in cols:
            out.append(f"    [\n{rows(c, '      ')}\n    ],")
        out.append("  ],")
        for part, vals in zip("LMS", (L, M, S)):
            out.append(f"  {part}: [\n{rows(vals, '    ')}\n  ],")
        out.append("};")
    for name, (L, M, S) in MUAC.items():
        out.append(f"export const {name}: Lms = {{")
        for part, vals in zip("LMS", (L, M, S)):
            out.append(f"  {part}: [\n{rows(vals, '    ')}\n  ],")
        out.append("};")
    return "\n".join(out) + "\n"


def kt():
    out = ["package kallam.healthcare.data", "", f"// {HEAD}", f"// {NOTE_IAP}", f"// {NOTE_MUAC}",
           "internal object GrowthRefTables {",
           "    class Iap(val labels: List<String>, val percents: List<Double>, val centiles: List<DoubleArray>, val lms: WhoTables.Lms)"]
    for name, (labels, pct, cols, L, M, S) in IAP.items():
        out.append(f"    val {name} = Iap(")
        out.append("        listOf(" + ", ".join(f'"{x}"' for x in labels) + "),")
        out.append("        listOf(" + ", ".join(f"{x}.0" for x in pct) + "),")
        out.append("        listOf(")
        for c in cols:
            out.append(f"            doubleArrayOf(\n{rows(c, '                ')}\n            ),")
        out.append("        ),")
        out.append("        WhoTables.Lms(")
        for vals in (L, M, S):
            out.append(f"            doubleArrayOf(\n{rows(vals, '                ')}\n            ),")
        out.append("        ),")
        out.append("    )")
    for name, t in MUAC.items():
        out.append(f"    val {name} = WhoTables.Lms(")
        for vals in t:
            out.append(f"        doubleArrayOf(\n{rows(vals, '            ')}\n        ),")
        out.append("    )")
    out.append("}")
    return "\n".join(out) + "\n"


def swift():
    out = [f"// {HEAD}", f"// {NOTE_IAP}", f"// {NOTE_MUAC}",
           "enum GrowthRefTables {",
           "    struct Iap { let labels: [String]; let percents: [Double]; let centiles: [[Double]]; let lms: WhoTables.Lms }"]
    for name, (labels, pct, cols, L, M, S) in IAP.items():
        out.append(f"    static let {name} = Iap(")
        out.append("        labels: [" + ", ".join(f'"{x}"' for x in labels) + "],")
        out.append("        percents: [" + ", ".join(f"{x}" for x in pct) + "],")
        out.append("        centiles: [")
        for c in cols:
            out.append(f"            [\n{rows(c, '                ')}\n            ] as [Double],")
        out.append("        ],")
        out.append("        lms: WhoTables.Lms(")
        for i, (lab, vals) in enumerate(zip("lms", (L, M, S))):
            comma = "," if i < 2 else ""
            out.append(f"            {lab}: [\n{rows(vals, '                ')}\n            ] as [Double]{comma}")
        out.append("        )")
        out.append("    )")
    for name, t in MUAC.items():
        out.append(f"    static let {name} = WhoTables.Lms(")
        for i, (lab, vals) in enumerate(zip("lms", t)):
            comma = "," if i < 2 else ""
            out.append(f"        {lab}: [\n{rows(vals, '            ')}\n        ] as [Double]{comma}")
        out.append("    )")
    out.append("}")
    return "\n".join(out) + "\n"


def write(rel, text):
    with open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", rel)


write("functions/growthrefs-data.ts", ts())
write("android/app/src/main/java/kallam/healthcare/data/GrowthRefTables.kt", kt())
write("ios/VitaHero/Models/GrowthRefTables.swift", swift())
