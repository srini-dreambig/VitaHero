#!/usr/bin/env python3
"""
Generate the iOS app's Localizable.strings from the Android app's strings.

The Android app's LocaleStrings.kt is the one place English, Hindi and Telugu
are kept, and the two apps should say the same thing in all three. So the iOS
files are generated from it rather than translated a second time, and the keys
are the same keys (`badge_super_eater`, `otp_title`, ...).

Strings only the iOS app needs live in ios/tools/ios_strings.json, one object
per language, and are appended after the Android ones.

Run from the repository root:

    python ios/tools/gen_strings.py
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
KT = ROOT / "android/app/src/main/java/kallam/healthcare/data/LocaleStrings.kt"
EXTRA = ROOT / "ios/tools/ios_strings.json"
OUT = ROOT / "ios/VitaHero/Resources"

LANGS = {"en": "en", "hi": "hi", "te": "te"}

# One or more Kotlin string literals joined by `+`.
LITERALS = r'((?:"(?:[^"\\]|\\.)*"\s*\+?\s*)+)'


def kotlin_string(src: str) -> str:
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', src)
    raw = "".join(parts)
    # Kotlin escapes are a subset of Python's; \$ is Kotlin-only.
    raw = raw.replace("\\$", "$")
    return raw.encode("latin-1", "backslashreplace").decode("unicode_escape")


def to_ios_format(value: str) -> str:
    # Kotlin's String.format takes %s; Foundation's takes %@.
    value = re.sub(r"%(\d+\$)?s", lambda m: "%" + (m.group(1) or "") + "@", value)
    return value


def strings_literal(value: str) -> str:
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
    )


def main() -> int:
    text = KT.read_text(encoding="utf-8")
    names = dict(re.findall(r'const val (\w+) = "([^"]+)"', text))

    extra = json.loads(EXTRA.read_text(encoding="utf-8")) if EXTRA.exists() else {}

    for kt_lang, ios_lang in LANGS.items():
        start = re.search(rf"private val {kt_lang} = mapOf\(", text)
        if not start:
            print(f"no map for {kt_lang}", file=sys.stderr)
            return 1
        body = text[start.end():]
        body = body[: re.search(r"\n\)\n", body).start()]

        entries: dict[str, str] = {}
        for name, lit in re.findall(r"S\.(\w+)\s+to\s+" + LITERALS, body):
            key = names.get(name)
            if key:
                entries[key] = to_ios_format(kotlin_string(lit))
        for key, value in extra.get(ios_lang, {}).items():
            entries[key] = value

        folder = OUT / f"{ios_lang}.lproj"
        folder.mkdir(parents=True, exist_ok=True)
        lines = [
            "/* Generated by ios/tools/gen_strings.py from the Android app's",
            "   LocaleStrings.kt and ios/tools/ios_strings.json. Do not edit. */",
            "",
        ]
        for key in sorted(entries):
            lines.append(f'"{key}" = "{strings_literal(entries[key])}";')
        (folder / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{ios_lang}: {len(entries)} strings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
